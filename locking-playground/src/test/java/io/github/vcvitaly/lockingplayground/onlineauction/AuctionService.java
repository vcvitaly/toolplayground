package io.github.vcvitaly.lockingplayground.onlineauction;

import org.springframework.jdbc.core.JdbcTemplate;

public record AuctionService(JdbcTemplate jdbcTemplate) {

    public void createTablesAndInitAuction() {
        jdbcTemplate.execute("""
                                    CREATE TABLE auctions (
                                         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
                                         current_highest_price INT,
                                         updated_at timestamp
                                    );
                                    """);
        jdbcTemplate.execute("""
                                    CREATE TABLE bids (
                                         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
                                         current_highest_price INT,
                                         updated_at timestamp,
                                         auction_id INT,
                                         FOREIGN KEY(auction_id)
                                                REFERENCES auctions(id)
                                                ON DELETE CASCADE
                                    );
                                    """);
        jdbcTemplate.update("INSERT INTO auctions (current_highest_price, updated_at) values (0, NOW())");
    }

    public void deleteTables() {
        jdbcTemplate.execute("DROP TABLE bids; DROP TABLE auctions;");
    }

    public int updateAuction(int id, int newPrice) {
        return jdbcTemplate.update("UPDATE auctions SET current_highest_price = ? where id = ?", newPrice, id);
    }

    public int createBid(int auctionId, int newPrice) {
        return jdbcTemplate.update("INSERT INTO bids (current_highest_price, updated_at, auction_id) values (?, NOW(), ?)", newPrice, auctionId);
    }

    public int getAuctionPrice(int auctionId) {
        return jdbcTemplate.queryForObject("SELECT current_highest_price FROM auctions where id = ?", Integer.class, auctionId);
    }
}
