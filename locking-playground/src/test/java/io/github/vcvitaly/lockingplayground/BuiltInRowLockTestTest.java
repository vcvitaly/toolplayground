package io.github.vcvitaly.lockingplayground;

import lombok.extern.slf4j.Slf4j;
import org.junit.jupiter.api.RepeatedTest;
import org.slf4j.Logger;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.transaction.support.TransactionTemplate;

import java.util.concurrent.CompletableFuture;

import static org.assertj.core.api.Assertions.assertThat;

@Slf4j
class BuiltInRowLockTestTest extends AbstractPostgresTest {

    @Autowired
    private JdbcTemplate jdbcTemplate;

    @RepeatedTest(10)
    void test() {
        jdbcTemplate.execute("""
                                    CREATE TABLE kv (
                                         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
                                         value int4
                                    );
                                    """);
        jdbcTemplate.update("insert into kv (value) values (0)");


        TransactionTemplate t1 = new TransactionTemplate(txManager);
        TransactionTemplate t2 = new TransactionTemplate(txManager);

        int interationsPerThread = 50;
        CompletableFuture<Void> cf1 = CompletableFuture.runAsync(() -> {
            for (int i = 0; i < interationsPerThread; i++) {
                t1.execute(_ -> {
                    jdbcTemplate.update("update kv set value = value + 1");
                    return null;
                });
            }
        });

        CompletableFuture<Void> cf2 = CompletableFuture.runAsync(() -> {
            for (int i = 0; i < interationsPerThread; i++) {
                t2.execute(_ -> {
                    jdbcTemplate.update("update kv set value = value + 1");
                    return null;
                });
            }
        });

        CompletableFuture.allOf(cf1, cf2).join();
        assertThat(jdbcTemplate.queryForObject("select value from kv where id = 1", Integer.class))
                .isEqualTo(100);

        jdbcTemplate.execute("drop table kv");
    }

    @Override
    protected Logger getLog() {
        return log;
    }
}